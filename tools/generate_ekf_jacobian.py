"""Derive a model Jacobian on the host and emit a plain C++ evaluator.

SymPy is a development dependency only. The generated header contains numeric
arithmetic and does not require SymPy or automatic differentiation at runtime.
"""

from __future__ import annotations

import re
from collections.abc import Sequence

import sympy as sp
from sympy.printing.cxx import cxxcode


_CPP_KEYWORDS = frozenset(
    "alignas alignof and and_eq asm auto bitand bitor bool break case catch char "
    "char16_t char32_t class compl const constexpr const_cast continue decltype "
    "default delete do double dynamic_cast else enum explicit export extern false "
    "float for friend goto if inline int long mutable namespace new noexcept not "
    "not_eq nullptr operator or or_eq private protected public register "
    "reinterpret_cast return short signed sizeof static static_assert static_cast "
    "struct switch template this thread_local throw true try typedef typeid "
    "typename union unsigned using virtual void volatile wchar_t while xor xor_eq"
    .split()
)


def _identifier(name: str) -> str:
    if (
        not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name)
        or "__" in name
        or name in _CPP_KEYWORDS
    ):
        raise ValueError(f"Not a usable C++ identifier: {name!r}")
    return name


def _symbols(symbols: Sequence[sp.Symbol], label: str) -> tuple[sp.Symbol, ...]:
    result = tuple(symbols)
    if any(not isinstance(symbol, sp.Symbol) for symbol in result):
        raise ValueError(f"{label} must contain SymPy Symbol objects")
    if len(set(result)) != len(result):
        raise ValueError(f"{label} must not contain duplicate symbols")
    return result


def derive_jacobian(
    model: sp.MatrixBase, state_symbols: Sequence[sp.Symbol]
) -> sp.Matrix:
    """Differentiate a column-vector model once, before generating firmware.

    For continuous dynamics this returns A = df/dx; for a discrete next-state
    model it returns F = df_d/dx. The caller chooses the model and coordinates.
    """
    states = _symbols(state_symbols, "state_symbols")
    if not states or not isinstance(model, sp.MatrixBase) or model.cols != 1:
        raise ValueError("Supply a nonempty column-vector model and state symbols")
    if model.rows == 0:
        raise ValueError("The model must have at least one output")
    return model.jacobian(states)


def generate_jacobian_header(
    jacobian: sp.MatrixBase,
    state_symbols: Sequence[sp.Symbol],
    parameter_symbols: Sequence[sp.Symbol] = (),
    *,
    namespace: str,
    function_name: str,
    context_name: str,
) -> str:
    """Emit an inline evaluator for an already derived symbolic Jacobian.

    The generated callback accepts (const Eigen::VectorXd&, Eigen::MatrixXd&,
    void*). state_symbols names its numeric inputs; the Jacobian's column count
    is independent, allowing a previously derived error-coordinate Jacobian to
    be evaluated from a larger nominal state. Its output must already have the
    generated dimensions. Parameters
    become double fields in the context struct, in the supplied order. A model
    with parameters requires a nonnull context. All inputs, parameters, and
    computed entries must be finite; dimensions are checked before any writes.
    """
    states = _symbols(state_symbols, "state_symbols")
    parameters = _symbols(parameter_symbols, "parameter_symbols")
    if set(states) & set(parameters):
        raise ValueError("State and parameter symbols must be distinct")
    if (
        not states
        or not isinstance(jacobian, sp.MatrixBase)
        or jacobian.rows == 0
        or jacobian.cols == 0
    ):
        raise ValueError("Supply a nonempty Jacobian and numeric input symbols")
    undeclared = jacobian.free_symbols - set(states) - set(parameters)
    if undeclared:
        raise ValueError(f"Undeclared symbols in Jacobian: {undeclared}")
    if len({str(symbol) for symbol in parameters}) != len(parameters):
        raise ValueError("Parameter field names must be distinct")
    for symbol in parameters:
        _identifier(str(symbol))
    for part in namespace.split("::"):
        _identifier(part)
    _identifier(function_name)
    _identifier(context_name)
    if function_name == context_name:
        raise ValueError("Function and context names must differ")

    # Internal names do not depend on symbolic names, avoiding C++ collisions.
    replacements = {
        symbol: sp.Symbol(f"astra_codegen_state_{index}")
        for index, symbol in enumerate(states)
    }
    replacements.update(
        {
            symbol: sp.Symbol(f"astra_codegen_parameter_{index}")
            for index, symbol in enumerate(parameters)
        }
    )
    lines = [
        "// Generated by tools/generate_ekf_jacobian.py. Do not edit by hand.",
        "// Symbolic differentiation happens on the host; evaluation uses doubles.",
        "#pragma once",
        "#include <ArduinoEigen.h>",
        "#include <cmath>",
        'extern "C" {',
        "#include <numx/autodiff.h>",
        "}",
        "",
        f"namespace {namespace} {{",
        "",
        f"struct {context_name} {{",
    ]
    lines.extend(f"    double {symbol};" for symbol in parameters)
    lines.extend(
        [
            "};",
            "",
            f"inline numx_status_t {function_name}(const Eigen::VectorXd &input,",
            "                                    Eigen::MatrixXd &jacobian, void *context)",
            "{",
            f"    if (input.size() != {len(states)} ||",
            f"        jacobian.rows() != {jacobian.rows} || jacobian.cols() != {jacobian.cols} ||",
            "        !input.allFinite()) {",
            "        return NUMX_ERR_INVALID_ARG;",
            "    }",
        ]
    )
    if parameters:
        lines.extend(
            [
                "    if (context == nullptr) {",
                "        return NUMX_ERR_NULL_PTR;",
                "    }",
                f"    const auto &parameters = *static_cast<const {context_name} *>(context);",
            ]
        )
        finite_conditions = " || ".join(
            f"!std::isfinite(parameters.{symbol})" for symbol in parameters
        )
        lines.extend(
            [
                f"    if ({finite_conditions}) {{",
                "        return NUMX_ERR_INVALID_ARG;",
                "    }",
            ]
        )
    else:
        lines.append("    (void)context;")
    for index, symbol in enumerate(states):
        if symbol in jacobian.free_symbols:
            lines.append(f"    const double {replacements[symbol]} = input({index});")
    for symbol in parameters:
        if symbol in jacobian.free_symbols:
            lines.append(
                f"    const double {replacements[symbol]} = parameters.{symbol};"
            )
    for row in range(jacobian.rows):
        for column in range(jacobian.cols):
            expression = jacobian[row, column].xreplace(replacements)
            # Avoid nonstandard constants such as M_PI in generated C++.
            expression = expression.xreplace(
                {
                    constant: sp.Float(constant.evalf(17), 17)
                    for constant in expression.atoms(sp.NumberSymbol)
                }
            )
            code = cxxcode(expression, standard="c++17")
            lines.append(f"    jacobian({row}, {column}) = {code};")
    lines.extend(
        [
            "    return jacobian.allFinite() ? NUMX_OK : NUMX_ERR_INVALID_ARG;",
            "}",
            "",
            f"}} // namespace {namespace}",
            "",
        ]
    )
    return "\n".join(lines)
